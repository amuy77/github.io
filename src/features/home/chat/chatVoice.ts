export type ChatSlot = keyof typeof CHAT_LINES

// 同じ場面で、同じセリフが 2 回続かないように
const last: Partial<Record<ChatSlot, string>> = {}

/** 場面のセリフを 1 つ選び、{変数} を埋める。入れる言葉（店主が打った文など）の中の {…} はそのまま */
export function chatLine(slot: ChatSlot, vars: Record<string, string | number> = {}, r: () => number = Math.random): string {
  const pool: string[] = CHAT_LINES[slot]
  let s = pool[Math.floor(r() * pool.length)]
  if (s === last[slot] && pool.length > 1) s = pool[(pool.indexOf(s) + 1) % pool.length]
  last[slot] = s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
